#!/usr/bin/env python3
"""batch-scans-md.py <batch-scans.tsv> <results-root> <out.md> — the Sprint 270 contamination hand-read table. Each unit gets a mechanism class
from its trigger (heuristic first, then the lead's hand-read overrides keyed by unit); anything unmatched is flagged UNCLASSIFIED for a hand read."""
import sys, csv, json, os, re, collections
tsv, root, out = sys.argv[1:4]
ABS = re.compile(r"(?:(?<=^)|(?<=[\s=:'\"`(<>|;&,]))(/[A-Za-z0-9._@+%=,:~-][A-Za-z0-9._@+%=,:~/-]*)")
HD = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1[^\n]*\n.*?\n\s*\2[ \t]*(?=\n|$)", re.S)
OK = ("/workspace", "/tmp", "/home/evaluser", "/dev", "/proc", "/sys", "/usr", "/bin", "/sbin", "/lib", "/lib64", "/etc", "/opt", "/var")
CLASSES = {
  "R": "reach for the upstream repository (clone, ls-remote, or a fetch of main) — the leak class 9 exists for",
  "T": "tool download or connectivity probe not naming the repository (jq 1.7.1 from github.com/jqlang; curl -I github.com)",
  "W": "a report written through a cat heredoc quoting PR text that carries the repository token (class 7, AG-53)",
  "S": "fictional paths or the repository token inside test inputs the reviewer fed to the PR's own guard or grader code",
  "P": "an environment probe for executable scratch space or mounts (/tmp is noexec, the root read-only)",
  "A": "a deliberately absent path in an errexit or fallback probe (/nonexistent/...)",
  "F": "GRADER FALSE POSITIVE: a sed/awk address or substitution regex (/re/d, /re/p, /re/g) tokenised as a two-component path",
  "K": "took-effect FAIL caused by PR code the agent executed (KF-053)",
}
def trigger(rd, excerpt):
    ph, _, ln = excerpt.partition(":")
    p = os.path.join(rd, "transcripts", "events-%s.jsonl" % ph)
    cmd = ""
    if ln.isdigit() and os.path.isfile(p):
        for i, line in enumerate(open(p, errors="replace"), 1):
            if i == int(ln):
                for b in (json.loads(line).get("message") or {}).get("content") or []:
                    if isinstance(b, dict) and b.get("type") == "tool_use":
                        inp = b.get("input") or {}
                        cmd = inp.get("command") or inp.get("file_path") or inp.get("url") or ""
                break
    words = []
    for m in ABS.finditer(HD.sub("", cmd)):
        w = m.group(1); n = os.path.normpath(w)
        if any(n == o or n.startswith(o + "/") for o in OK):
            continue
        if re.match(r"^/[^/]+/?$", w) and w.strip("/") not in ("root", "home", "mnt", "media", "srv"):
            continue
        words.append(w)
    return cmd, sorted(set(words))
def classify(r, cmd, words):
    pat = r["pattern"]
    if pat == "network_egress":
        return "R" if r["repo_named"] == "True" else "T"
    if pat == "repo_name":
        return "W" if re.search(r"cat\s+>\s*\S+\s*<<", cmd) and "python" not in cmd.split("<<")[0] else "S"
    if pat == "outside_path":
        if any(re.match(r"^/[^/]+/[dpgs]$", w) for w in words):
            return "F"
        if any(w.startswith("/nonexistent") for w in words):
            return "A"
        if any(w in ("/home", "/workspace/..", "/workspace/../scratch") for w in words):
            return "P"
        if words or "python" in cmd or "<<" in cmd:
            return "S"
    return "?"
rows = list(csv.DictReader(open(tsv), delimiter="\t"))
# lead hand-read overrides (unit key = batch/arm/unit/session)
OVERRIDE = {"c132-g1-a2/a0_bare_matched/review-r27-t1/s3": "S"}
# took-effect FAILs on matched sessions (invalid, not contaminated): enumerate from the session records
import glob
for rec in sorted(glob.glob(os.path.join(root, "c132-g[1-9]-*", "*", "*", "meta", "sessions", "s*.json"))):
    try:
        j = json.load(open(rec))
    except Exception:
        continue
    if "took-effect" in str(j.get("invalid_reason") or ""):
        parts = os.path.relpath(rec, root).split(os.sep)
        rows.append({"batch": parts[0], "arm": parts[1], "unit": parts[2], "session": j.get("id", ""), "pattern": "took_effect",
                     "excerpt": "", "repo_named": "", "host": "", "command": str(j.get("invalid_reason"))[:200]})
L = ["# Sprint 270 — contamination hand-reads (every contaminated Phase 1 unit)\n\n",
     "Generated by `~/.cache/loa/cycle-132/scripts/batch-scans-md.py` from the c132-g* batches; every unit stays invalid on the primary as registered (§4; DEC-0791); the per-class sensitivity rows (addendum 8) re-include them by grader class. The mechanism column is the lead's hand-read class.\n\n",
     "| class | mechanism |\n|---|---|\n"] + ["| %s | %s |\n" % kv for kv in CLASSES.items()]
cnt = collections.Counter(); byarm = collections.defaultdict(collections.Counter)
body = ["\n| batch | arm | unit | session | grader class | trigger | mechanism |\n|---|---|---|---|---|---|---|\n"]
for r in rows:
    unit = r["unit"] + ("/sessions/" + r["session"] if r["session"] else "")
    cmd, words = trigger(os.path.join(root, r["batch"], r["arm"], unit), r["excerpt"])
    c = "K" if r["pattern"] == "took_effect" else classify(r, cmd, words)
    c = OVERRIDE.get("/".join([r["batch"], r["arm"], r["unit"], r["session"]]), c)
    if r["pattern"] == "took_effect":
        words = [r["command"][:80]]
    cnt[c] += 1; byarm[r["arm"]][c] += 1
    trig = (r["host"] + " " if r["host"] else "") + (" ".join(words)[:80] if words else "")
    if r["pattern"] == "network_egress":
        m = re.search(r"https?://\S+", cmd); trig = (m.group(0)[:90] if m else trig)
    body.append("| %s | %s | %s | %s | %s | `%s` | %s |\n" % (r["batch"], r["arm"], r["unit"], r["session"] or "—", r["pattern"], trig.replace("|", "\\|").strip() or "(heredoc or quoted body)", "**" + c + "**" if c in ("R", "F", "?") else c))
L.append("\n## Counts\n\n| arm | " + " | ".join(CLASSES) + " | ? | total |\n|---|" + "---|" * (len(CLASSES) + 2) + "\n")
for arm in sorted(byarm):
    L.append("| %s | %s | %d | %d |\n" % (arm, " | ".join(str(byarm[arm][k]) for k in CLASSES), byarm[arm]["?"], sum(byarm[arm].values())))
L.append("| all | %s | %d | %d |\n" % (" | ".join(str(cnt[k]) for k in CLASSES), cnt["?"], sum(cnt.values())))
L += body
open(out, "w").write("".join(L))
print(dict(cnt))
